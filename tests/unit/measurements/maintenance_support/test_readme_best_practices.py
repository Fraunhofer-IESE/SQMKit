@pytest.mark.anyio
@pytest.mark.parametrize("anyio_backend", ["asyncio"])
async def test_readme_best_practice_good_readme(
    repo_dir: RepoDir, make_model_client: Callable[..., ModelClient]
):
    await repo_dir.add_file("README.md", GOOD_README)

    measurement = ReadmeBestPractices(repo_dir, make_model_client(score=5))
    result = await measurement.execute()

    assert result.score > 0.5
    assert "Evaluation of the README file:" in result.reason


@pytest.mark.anyio
@pytest.mark.parametrize("anyio_backend", ["asyncio"])
async def test_readme_best_practice_empty_readme(
    repo_dir: RepoDir, make_model_client: Callable[..., ModelClient]
):
    await repo_dir.add_file("README.md", "")

    measurement = ReadmeBestPractices(repo_dir, make_model_client(score=5))
    result = await measurement.execute()

    assert result.status is EvaluationStatus.EVALUATED
    assert result.score == 0.0
    assert "empty" in result.reason.lower()


@pytest.mark.anyio
@pytest.mark.parametrize("anyio_backend", ["asyncio"])
async def test_readme_best_practice_poor_readme(
    repo_dir: RepoDir, make_model_client: Callable[..., ModelClient]
):
    await repo_dir.add_file("README.md", POOR_README)

    measurement = ReadmeBestPractices(repo_dir, make_model_client(score=1))
    result = await measurement.execute()

    assert result.score < 0.5
    assert "Evaluation of the README file:" in result.reason
